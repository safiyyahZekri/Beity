// Requested dates are stored as ISO `YYYY-MM-DD` (that's what the calendar
// picker produces). Seeding them relative to today keeps the demo from ever
// showing a request for a date that has already passed.
function daysFromNow(n) {
  const d = new Date()
  d.setDate(d.getDate() + n)
  const pad = (x) => String(x).padStart(2, '0')
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`
}

